#!/usr/bin/env python3
"""Independent verification + integration after the overnight workers end (spec R9, R10, R7).

For each task (merge order from tasks.json) it checks, without trusting the worker:
  (a) changed files are inside the task's owned paths   (b) no attribution text in any commit message
  (c) the worktree is clean                              (d) tests pass on a fresh verify run, test count >= floor
  (e) task 4 screenshots exist                           (f) task 5 validator passes
Only tasks whose worker 'finished' AND pass every check are merged into night/integration (never main).
Everything else is recorded with reasons and preserved. Recovery entries for unmerged tasks 1-4 go into
features.json (or docs/night/recovery-tasks.json if task 5 was not merged). Writes and commits the morning report.
"""
import argparse, datetime, json, os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PARENT = os.path.dirname(REPO)
NIGHT = os.path.join(PARENT, "ios-night")
STATE = os.path.join(NIGHT, "_state")
INTEG = os.path.join(NIGHT, "integration")
BASE = "night-2026-11-11-base"
VSIM = "bgt-night-verify"
REPORT_REL = "docs/night/2026-11-11-report.md"
ATTRIBUTION = re.compile(r"co-authored-by|generated with|generated by claude|claude code|noreply@anthropic\.com", re.I)
CFG = json.load(open(os.path.join(HERE, "tasks.json")))
TASKS = {t["n"]: t for t in CFG["tasks"]}


def sh(args, cwd=REPO, check=False, env=None):
    p = subprocess.run(args, cwd=cwd, capture_output=True, text=True, env=env)
    if check and p.returncode != 0:
        raise RuntimeError(f"{' '.join(args)} failed: {p.stderr.strip()[:400]}")
    return p


def log(msg):
    line = f"[{datetime.datetime.now():%H:%M:%S}] integrate: {msg}"
    print(line, flush=True)
    with open(os.path.join(STATE, "run.log"), "a") as f:
        f.write(line + "\n")


def in_scope(path, owned):
    return any(path.startswith(o) if o.endswith("/") else path == o for o in owned)


def run_verify(cwd):
    env = dict(os.environ, BGT_STATE_DIR=STATE)
    p = sh(["./scripts/verify.sh", VSIM], cwd=cwd, env=env)
    try:
        latest = json.load(open(os.path.join(cwd, "build/results/latest.json")))
    except Exception:
        latest = {"rc": p.returncode, "executed": 0, "failures": -1}
    last = (p.stdout.strip().splitlines() or ["(no output)"])[-1]
    return p.returncode == 0, latest, last


def check_task(n, status):
    t = TASKS[n]; slug = t["slug"]; br = f"night/{slug}"; wt = os.path.join(NIGHT, slug)
    r = {"n": n, "slug": slug, "branch": br, "worker": status.get("state"), "checks": {}, "reasons": [],
         "cost_usd": status.get("cost_usd"), "turns": status.get("num_turns"), "tests": None}
    if status.get("state") != "finished":
        r["reasons"].append(f"worker {status.get('state')} (rc={status.get('rc')}, result={status.get('result_subtype')})")
    commits = sh(["git", "rev-list", f"{BASE}..{br}"]).stdout.split()
    r["commits"] = len(commits)
    if not commits:
        r["reasons"].append("no commits on branch")
    # (a) scope
    changed = [x for x in sh(["git", "diff", "--name-only", f"{BASE}...{br}"]).stdout.splitlines() if x]
    out = [x for x in changed if not in_scope(x, t["owned"])]
    r["checks"]["a_scope"] = not out
    if out: r["reasons"].append(f"files outside owned paths: {out[:8]}")
    # (b) commit messages
    msgs = sh(["git", "log", "--format=%H%n%B%n--END--", f"{BASE}..{br}"]).stdout
    bad = ATTRIBUTION.findall(msgs)
    r["checks"]["b_messages"] = not bad
    if bad: r["reasons"].append(f"attribution text in commit messages: {sorted(set(b.lower() for b in bad))}")
    # (c) clean worktree
    dirty = sh(["git", "status", "--porcelain"], cwd=wt).stdout.strip() if os.path.isdir(wt) else "missing worktree"
    r["checks"]["c_clean"] = not dirty
    if dirty: r["reasons"].append("worktree not clean (uncommitted work preserved in _state)")
    # Don't spend build time on branches that can't merge anyway.
    if r["reasons"]:
        return r
    # (d) tests
    if t.get("test_dir"):
        grep = sh(["git", "grep", "-c", r"func test", br, "--", t["test_dir"]]).stdout
        count = sum(int(l.rsplit(":", 1)[1]) for l in grep.splitlines() if ":" in l)
        r["test_funcs"] = count
        if count < t["min_tests"]:
            r["reasons"].append(f"only {count} test functions in {t['test_dir']} (need {t['min_tests']})")
        log(f"task {n}: running verify on {VSIM}")
        passed, latest, last = run_verify(wt)
        r["tests"] = latest; r["checks"]["d_tests"] = passed and count >= t["min_tests"]
        if not passed:
            log(f"task {n}: verify failed ({last}); rerunning once alone")
            passed, latest, last = run_verify(wt)
            r["tests"] = latest; r["checks"]["d_tests"] = passed and count >= t["min_tests"]
            if not passed: r["reasons"].append(f"verify failed twice: {last}")
    # (e) screenshots
    for shot in t.get("screenshots", []):
        exists = sh(["git", "cat-file", "-e", f"{br}:{shot}"]).returncode == 0
        r["checks"].setdefault("e_screens", True)
        if not exists:
            r["checks"]["e_screens"] = False; r["reasons"].append(f"missing {shot}")
    # (f) validator
    if t.get("validator"):
        p = sh(t["validator"].split(), cwd=wt)
        r["checks"]["f_validator"] = p.returncode == 0
        r["validator"] = (p.stdout.strip().splitlines() or [""])[-1] if p.returncode == 0 else p.stdout.strip()[:1500]
        if p.returncode != 0: r["reasons"].append("parity validator failed")
    return r


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--total-deadline", type=int, required=True)
    args = ap.parse_args()
    results, merged = {}, []

    if os.path.exists(INTEG) or sh(["git", "rev-parse", "-q", "--verify", "refs/heads/night/integration"]).returncode == 0:
        log("night/integration already exists; refusing to reuse it"); return 2
    sh(["git", "worktree", "add", "-q", "-b", "night/integration", INTEG, BASE], check=True)

    for n in CFG["merge_order"]:
        try:
            status = json.load(open(os.path.join(STATE, f"{n}.status.json")))
        except Exception:
            status = {"state": "never-started"}
        if time.time() > args.total_deadline:
            results[n] = {"n": n, "slug": TASKS[n]["slug"], "branch": f"night/{TASKS[n]['slug']}", "worker": status.get("state"),
                          "checks": {}, "reasons": ["total deadline reached before verification"], "merged": False}
            continue
        r = check_task(n, status)
        r["merged"] = False
        if not r["reasons"]:
            p = sh(["git", "merge", "--no-ff", "-m", f"Merge {r['branch']} (overnight task {n})", r["branch"]], cwd=INTEG)
            if p.returncode == 0:
                r["merged"] = True; merged.append(n); log(f"task {n}: merged")
            else:
                sh(["git", "merge", "--abort"], cwd=INTEG)
                r["reasons"].append(f"merge conflict: {p.stdout.strip()[-300:]}")
        if not r["merged"]:
            log(f"task {n}: NOT merged: {'; '.join(r['reasons'])}")
        results[n] = r

    # Recovery entries: missing work is never treated as done.
    unmerged = [n for n in (1, 2, 3, 4) if not results.get(n, {}).get("merged")]
    recovery_note = None
    if unmerged or not results.get(5, {}).get("merged"):
        entries = [dict(TASKS[n]["recovery"], note=f"Overnight 2026-11-11 not merged: {'; '.join(results.get(n, {}).get('reasons', ['not run']))}. "
                                                     f"Preserved on branch night/{TASKS[n]['slug']}.") for n in unmerged]
        fj = os.path.join(INTEG, "harness/features.json")
        if results.get(5, {}).get("merged") and os.path.isfile(fj):
            data = json.load(open(fj)); data["tasks"] = entries + data["tasks"]
            json.dump(data, open(fj, "w"), indent=2); open(fj, "a").write("\n")
            v = sh(["python3", "harness/night/validate_parity.py"], cwd=INTEG)
            recovery_note = f"Added {len(entries)} recovery task(s) to harness/features.json (validator: {(v.stdout.strip().splitlines() or [''])[-1]})"
            sh(["git", "add", "harness/features.json"], cwd=INTEG)
        else:
            entries.append(dict(TASKS[5]["recovery"], note="Overnight task 5 not merged; regenerate PARITY.md and features.json."))
            path = os.path.join(INTEG, "docs/night/recovery-tasks.json")
            os.makedirs(os.path.dirname(path), exist_ok=True)
            json.dump({"tasks": entries}, open(path, "w"), indent=2)
            recovery_note = f"Task 5 not merged: {len(entries)} recovery task(s) written to docs/night/recovery-tasks.json"
            sh(["git", "add", "docs/night/recovery-tasks.json"], cwd=INTEG)
        if entries:
            sh(["git", "commit", "-q", "-m", "Record unfinished overnight work as recovery tasks"], cwd=INTEG)

    # Full suite + screenshots on the integration branch.
    integ_tests, integ_shots = None, None
    if merged and time.time() <= args.total_deadline:
        log("running full suite on night/integration")
        ok, latest, last = run_verify(INTEG)
        integ_tests = {"passed": ok, "summary": last, **latest}
        if 4 in merged and ok:
            out = os.path.join(STATE, "integration-screens")
            p = sh(["./scripts/screenshots.sh", VSIM, out], cwd=INTEG)
            integ_shots = out if p.returncode == 0 else f"failed: {p.stdout.strip()[-200:]}"

    write_report(results, merged, recovery_note, integ_tests, integ_shots, args.total_deadline)
    sh(["git", "add", REPORT_REL], cwd=INTEG)
    sh(["git", "commit", "-q", "-m", "Overnight report 2026-11-11"], cwd=INTEG)
    log(f"done: merged {merged or 'nothing'}; report at {os.path.join(INTEG, REPORT_REL)}")
    return 0


def write_report(results, merged, recovery_note, integ_tests, integ_shots, deadline):
    L = ["# Overnight report: 2026-11-11", "",
         f"Generated {datetime.datetime.now():%Y-%m-%d %H:%M} by `harness/night/integrate.py`. Base: tag `{BASE}`.",
         "Nothing was pushed and nothing was merged into `main`. Merged branches are on the local branch `night/integration`.", "",
         "## Tasks", "",
         "| # | Task | Worker | Checks a/b/c/d/e/f | Tests (fresh run) | Cost | Merged | Reasons |",
         "|---|---|---|---|---|---|---|---|"]
    for n in CFG["merge_order"]:
        r = results.get(n, {})
        c = r.get("checks", {})
        marks = "/".join({True: "✓", False: "✗", None: "–"}[c.get(k)] for k in
                         ("a_scope", "b_messages", "c_clean", "d_tests", "e_screens", "f_validator"))
        tests = r.get("tests") or {}
        tcell = f"{tests.get('executed', '–')} run, {tests.get('failures', '–')} failed" if tests else (r.get("validator") or "–")
        cost = f"${r['cost_usd']:.2f}" if isinstance(r.get("cost_usd"), (int, float)) else "–"
        L.append(f"| {n} | `{r.get('branch', '')}` | {r.get('worker')} | {marks} | {tcell} | {cost} | "
                 f"{'yes' if r.get('merged') else '**no**'} | {'; '.join(r.get('reasons', [])) or '–'} |")
    L += ["", "Checks: a = changed files within owned paths, b = no attribution in commit messages, c = clean worktree,",
          "d = fresh `verify.sh` passes and test count meets the floor, e = screenshots exist (task 4), f = parity validator (task 5).", ""]
    L += ["## Integration branch", ""]
    if integ_tests:
        L.append(f"- Full suite on `night/integration`: {'PASS' if integ_tests['passed'] else 'FAIL'}: {integ_tests['summary']}")
    else:
        L.append("- Full suite not run (nothing merged, or the deadline passed).")
    if integ_shots: L.append(f"- Screenshots from the integration branch: `{integ_shots}`")
    if recovery_note: L.append(f"- {recovery_note}")
    L += ["", "## Unfinished work (preserved, not merged)", ""]
    any_unfinished = False
    for n in CFG["merge_order"]:
        r = results.get(n, {})
        if r.get("merged"): continue
        any_unfinished = True
        slug = TASKS[n]["slug"]
        extras = [f"branch `night/{slug}`", f"worktree `ios-night/{slug}`", f"log `ios-night/_state/logs/{slug}.jsonl`"]
        if os.path.exists(os.path.join(STATE, f"{n}.uncommitted.patch")):
            extras.append(f"uncommitted patch `ios-night/_state/{n}.uncommitted.patch`")
        L.append(f"- Task {n} ({slug}): " + ", ".join(extras))
    if not any_unfinished: L.append("- None.")
    L += ["", "## Worker reports", ""]
    for n in CFG["merge_order"]:
        L.append(f"- Task {n}: `docs/night/{TASKS[n]['slug']}.md` on `night/{TASKS[n]['slug']}`")
    L += ["", "## Decisions for you", "",
          "1. Which `night/*` branches (or `night/integration` as a whole) to merge into `main`.",
          "2. Review `docs/PARITY.md` and `harness/features.json` (the Night 0 review).",
          "3. Push `main` yourself when you're happy (the automation never pushes).", "",
          "## Next suggested tasks", ""]
    fj = os.path.join(INTEG, "harness/features.json")
    if os.path.isfile(fj):
        try:
            tasks = json.load(open(fj))["tasks"]
            ready = [t for t in tasks if t.get("status") == "todo" and not t.get("depends_on")][:5]
            L += [f"- `{t['id']}`: {t['title']}" for t in ready] or ["- (none without dependencies)"]
        except Exception as e:
            L.append(f"- could not read features.json: {e}")
    else:
        L.append("- features.json not available (task 5 not merged).")
    path = os.path.join(INTEG, REPORT_REL)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(L) + "\n")
    open(os.path.join(STATE, "report.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
