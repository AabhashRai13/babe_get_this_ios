#!/usr/bin/env python3
"""Independent verification + integration after a night's workers end.

For each task (config merge_order) it checks, without trusting the worker:
  (a) changed files are inside the task's owned paths   (b) no attribution text in any commit message
  (c) the worktree is clean                              (d) the task's acceptance commands from
      harness/features.json pass in the task worktree (simulator name substituted)
Passing tasks are merged one at a time into night/<id>/integration (never main/development). After EACH merge the
full suite runs on the integration branch; a merge that breaks it is undone (reset to the pre-merge commit) and the
task is reported as not merged. Merged tasks are marked status "done" in features.json; everything else stays "todo"
so missing work is never treated as complete. Writes and commits docs/night/<id>-report.md.
"""
import argparse, datetime, json, os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PARENT = os.path.dirname(REPO)
NIGHT = os.path.join(PARENT, "ios-night")
STATE = os.path.join(NIGHT, "_state")
VSIM = "bgt-night-verify"
ATTRIBUTION = re.compile(r"co-authored-by|generated with|generated by claude|claude code|noreply@anthropic\.com", re.I)


def sh(args, cwd=REPO, env=None, shell=False):
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, env=env, shell=shell)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--total-deadline", type=int, required=True)
    a = ap.parse_args()
    cfg = json.load(open(a.config))
    nid = cfg["night_id"]
    run = os.path.join(NIGHT, nid)
    runstate = os.path.join(run, "_run")
    integ = os.path.join(run, "integration")
    base = f"night-{nid}-base"
    ibranch = f"night/{nid}/integration"
    report_rel = f"docs/night/{nid}-report.md"
    tasks = {t["n"]: t for t in cfg["tasks"]}
    order = cfg.get("merge_order") or [t["n"] for t in cfg["tasks"]]
    env = dict(os.environ, BGT_STATE_DIR=STATE)

    def log(msg):
        line = f"[{datetime.datetime.now():%H:%M:%S}] [{nid}] integrate: {msg}"
        print(line, flush=True)
        with open(os.path.join(runstate, "run.log"), "a") as f:
            f.write(line + "\n")

    def in_scope(path, owned):
        return any(path.startswith(o) if o.endswith("/") else path == o for o in owned)

    def verify(cwd, extra=()):
        p = sh(["./scripts/verify.sh", VSIM, *extra], cwd=cwd, env=env)
        last = (p.stdout.strip().splitlines() or ["(no output)"])[-1]
        try:
            latest = json.load(open(os.path.join(cwd, "build/results/latest.json")))
        except Exception:
            latest = {}
        return p.returncode == 0, last, latest

    if os.path.exists(integ) or sh(["git", "rev-parse", "-q", "--verify", f"refs/heads/{ibranch}"]).returncode == 0:
        log(f"{ibranch} already exists; refusing to reuse it")
        return 2
    sh(["git", "worktree", "add", "-q", "-b", ibranch, integ, base])
    features = {t["id"]: t for t in json.load(open(os.path.join(integ, "harness/features.json")))["tasks"]}

    results, merged = {}, []
    last_full = None
    for n in order:
        t = tasks[n]
        slug, tid = t["slug"], t["id"]
        br, wt = f"night/{nid}/{slug}", os.path.join(run, slug)
        try:
            status = json.load(open(os.path.join(runstate, f"{n}.status.json")))
        except Exception:
            status = {"state": "never-started"}
        r = {"n": n, "id": tid, "slug": slug, "branch": br, "worker": status.get("state"), "cost": status.get("cost_usd"),
             "checks": {}, "acceptance": [], "reasons": [], "merged": False}
        results[n] = r
        if time.time() > a.total_deadline:
            r["reasons"].append("total deadline reached before verification"); continue
        if status.get("state") != "finished":
            r["reasons"].append(f"worker {status.get('state')} (rc={status.get('rc')}, result={status.get('result_subtype')})")
        commits = sh(["git", "rev-list", f"{base}..{br}"]).stdout.split()
        if not commits: r["reasons"].append("no commits on branch")
        changed = [x for x in sh(["git", "diff", "--name-only", f"{base}...{br}"]).stdout.splitlines() if x]
        out = [x for x in changed if not in_scope(x, t["owned"])]
        r["checks"]["a_scope"] = not out
        if out: r["reasons"].append(f"files outside owned paths: {out[:8]}")
        bad = ATTRIBUTION.findall(sh(["git", "log", "--format=%B", f"{base}..{br}"]).stdout)
        r["checks"]["b_messages"] = not bad
        if bad: r["reasons"].append(f"attribution text in commit messages: {sorted(set(b.lower() for b in bad))}")
        dirty = sh(["git", "status", "--porcelain"], cwd=wt).stdout.strip() if os.path.isdir(wt) else "missing"
        r["checks"]["c_clean"] = not dirty
        if dirty: r["reasons"].append("worktree not clean (uncommitted work preserved in _run)")
        if r["reasons"]:
            log(f"{tid}: not eligible: {'; '.join(r['reasons'])}"); continue

        # (d) acceptance commands from features.json, run in the task worktree
        ok_all = True
        for cmd in features[tid]["acceptance"]:
            c = cmd.replace('"iPhone 18 Pro"', VSIM).replace("'iPhone 18 Pro'", VSIM)
            p = sh(c, cwd=wt, env=env, shell=True)
            if p.returncode != 0:
                log(f"{tid}: acceptance failed, rerunning once alone: {c[:120]}")
                p = sh(c, cwd=wt, env=env, shell=True)
            line = (p.stdout.strip().splitlines() or [""])[-1]
            r["acceptance"].append({"cmd": c, "ok": p.returncode == 0, "out": line})
            if p.returncode != 0:
                ok_all = False; r["reasons"].append(f"acceptance failed: {c[:160]} -> {line}"); break
        r["checks"]["d_acceptance"] = ok_all
        if not ok_all:
            continue

        # merge, then prove the integration branch still passes; undo the merge if not
        before = sh(["git", "rev-parse", "HEAD"], cwd=integ).stdout.strip()
        p = sh(["git", "merge", "--no-ff", "-m", f"Merge {br} ({tid})", br], cwd=integ)
        if p.returncode != 0:
            sh(["git", "merge", "--abort"], cwd=integ)
            r["reasons"].append(f"merge conflict: {p.stdout.strip()[-300:]}"); continue
        log(f"{tid}: merged; running full suite on {ibranch}")
        ok, line, latest = verify(integ)
        if not ok:
            ok, line, latest = verify(integ)  # one rerun to rule out a flaky test
        r["checks"]["e_integration"] = ok
        if not ok:
            sh(["git", "reset", "-q", "--hard", before], cwd=integ)
            r["reasons"].append(f"breaks the integration branch, merge undone: {line}")
            log(f"{tid}: merge undone ({line})"); continue
        r["merged"] = True; merged.append(tid); last_full = line

    # Mark merged tasks done; unmerged stay todo (missing work is never treated as complete).
    if merged:
        fj = os.path.join(integ, "harness/features.json")
        data = json.load(open(fj))
        for task in data["tasks"]:
            if task["id"] in merged: task["status"] = "done"
        json.dump(data, open(fj, "w"), indent=2); open(fj, "a").write("\n")
        v = sh(["python3", "harness/night/validate_parity.py"], cwd=integ)
        sh(["git", "add", "harness/features.json"], cwd=integ)
        sh(["git", "commit", "-q", "-m", f"Mark {', '.join(merged)} done in features.json"], cwd=integ)
        validator_line = (v.stdout.strip().splitlines() or [""])[-1]
    else:
        validator_line = "not run (nothing merged)"

    # Report
    L = [f"# Overnight report: {nid}", "",
         f"Generated {datetime.datetime.now():%Y-%m-%d %H:%M} by `harness/night/integrate.py`. Base: `{cfg['base_ref']}` "
         f"(tag `{base}`). Nothing was pushed or merged into `main`/`development`.", "",
         "| Task | Branch | Worker | Scope / msgs / clean / acceptance / integration | Cost | Merged | Reasons |",
         "|---|---|---|---|---|---|---|"]
    for n in order:
        r = results.get(n, {}); c = r.get("checks", {})
        marks = " / ".join({True: "✓", False: "✗", None: "–"}[c.get(k)] for k in ("a_scope", "b_messages", "c_clean", "d_acceptance", "e_integration"))
        cost = f"${r['cost']:.2f}" if isinstance(r.get("cost"), (int, float)) else "–"
        L.append(f"| {r.get('id')} | `{r.get('branch')}` | {r.get('worker')} | {marks} | {cost} | "
                 f"{'yes' if r.get('merged') else '**no**'} | {'; '.join(r.get('reasons', [])) or '–'} |")
    L += ["", "## Acceptance results", ""]
    for n in order:
        for acc in results.get(n, {}).get("acceptance", []):
            L.append(f"- {results[n]['id']}: {'✓' if acc['ok'] else '✗'} `{acc['out']}`")
    L += ["", "## Integration branch", "",
          f"- Last full suite after a merge: {last_full or 'n/a'}",
          f"- features.json: {validator_line}", "",
          "## Unmerged work (preserved)", ""]
    any_un = False
    for n in order:
        r = results.get(n, {})
        if r.get("merged"): continue
        any_un = True
        extra = f", patch `ios-night/{nid}/_run/{n}.uncommitted.patch`" if os.path.exists(os.path.join(runstate, f"{n}.uncommitted.patch")) else ""
        L.append(f"- {r.get('id')}: branch `{r.get('branch')}`, log `ios-night/{nid}/_run/logs/{r.get('slug')}.jsonl`{extra}. Stays `todo`.")
    if not any_un: L.append("- None.")
    path = os.path.join(integ, report_rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(L) + "\n")
    open(os.path.join(runstate, "report.md"), "w").write("\n".join(L) + "\n")
    sh(["git", "add", report_rel], cwd=integ)
    sh(["git", "commit", "-q", "-m", f"Overnight report {nid}"], cwd=integ)
    json.dump({"merged": merged, "integration_branch": ibranch}, open(os.path.join(runstate, "results.json"), "w"))
    log(f"done: merged {merged or 'nothing'}; report at {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
