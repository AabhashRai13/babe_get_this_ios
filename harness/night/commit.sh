#!/usr/bin/env bash
# The only way an overnight worker commits. Workers may not run `git commit` directly (it accepts
# -n / abbreviated --no-verify, which skip the commit-msg hook).
#
# Usage: <repo>/harness/night/commit.sh "<one-line message>"     (run from the worker's worktree)
# Commits what is staged in the current directory's repository with exactly that message:
# - exactly one argument, a single non-empty line; anything else is rejected
# - attribution text is rejected here as well as by the hook
# - the hook path is forced to this checkout's scripts/git-hooks, whatever the repo config says
# - no auto gc/maintenance, so a commit writes only objects, the branch ref and this worktree's files
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOOKS="$(cd "$HERE/../../scripts/git-hooks" && pwd)"

die() { echo "commit.sh: $*" >&2; exit 2; }
[ "$#" -eq 1 ] || die "takes exactly one argument, the commit message (got $#)"
msg="$1"
[ -n "${msg//[[:space:]]/}" ] || die "empty message"
case "$msg" in *$'\n'*|*$'\r'*) die "the message must be one line" ;; esac
if printf '%s' "$msg" | grep -qiE 'co-authored-by|generated with|generated by claude|claude code|noreply@anthropic\.com'; then
  die "attribution/trailer text is not allowed in commit messages"
fi
[ -x "$HOOKS/commit-msg" ] || die "commit-msg hook missing at $HOOKS"

exec git -c core.hooksPath="$HOOKS" -c gc.auto=0 -c maintenance.auto=false -c commit.gpgsign=false \
  commit --quiet -m "$msg"
